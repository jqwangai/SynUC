"""Convert synthesized Syn-UC samples into supervised fine-tuning data."""

from __future__ import annotations

import argparse
from collections import Counter
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional

from . import conversion_utils as common
from .config import DATA_DIR, OUTPUT_PATH


DEFAULT_INPUT_PATH = Path(OUTPUT_PATH)
DEFAULT_OUTPUT_PATH = DATA_DIR / "training" / "sft.json"


CLASSIFICATION_PROMPT = """Your task is to classify the user's subsequent query, based on the given dialogue history, into one of the following types:

## Classification Definitions
### 1. Normal Dialogue
First understand the current main task, current subtask, historical explicit constraints, and historical implicit constraints from the dialogue history. If the subsequent query is compatible with the constraints that are still valid in the history and does not create a conflict that needs to be resolved, classify it as Normal Dialogue.
Common forms include:
- Normal continuation: a new request that naturally continues the previous topic or task
- Normal supplementation: a reasonable addition to, or refinement of, previous content
- Normal task switch: a switch to a completely new task request

### 2. Explicit Revision
Within the same task or a naturally continued task, if the subsequent query explicitly provides new explicit constraints that replace, override, or are incompatible with still-valid historical explicit constraints, classify it as Explicit Revision.
Corresponding conflict path:
- H_E_N_E: historical explicit constraints conflict with new explicit constraints in the subsequent query

### 3. Implicit Conflict
Within the same task or a naturally continued task, if the subsequent query does not explicitly state that it is revising earlier requirements, but the new constraints it introduces are incompatible with still-valid historical constraints, then it creates a conflict. A conflict exists only when two constraints cannot be satisfied at the same time; "different," "more detailed," "supplementary," or "expanded" does not by itself mean conflict.
Acceptable conflict paths include:
- H_E_N_I: historical explicit constraints conflict with new implicit constraints in the subsequent query
- H_I_N_E: historical implicit constraints conflict with new explicit constraints in the subsequent query
- H_I_N_I: historical implicit constraints conflict with new implicit constraints in the subsequent query

## Constraint Definitions
Explicit Constraints: requirements directly expressed by the user in the query and clearly identifiable from the literal text, including but not limited to topic, object scope, language, format, length, style, audience, output form, technology choice, input data, data source, method, and specific content restrictions.
Implicit Constraints: default requirements not directly stated by the user in the query, but naturally and stably inferable from the task goal, task type, usage scenario, entity attributes, domain norms, or common sense. Do not repeat requirements that the user has already stated explicitly as implicit constraints.

## Important Notes
- Focus only on user queries: during analysis, pay close attention to the relationship between user queries in the dialogue history and the current subsequent query.
- Ignore assistant responses: assistant responses should be used only as dialogue context. Do not treat content generated by the assistant as user constraints.

## Output Format
<think>
[Task Level]
Provide the task-level analysis.
If the subsequent query starts a new task, skip [Historical Constraints], [New Constraints], and [Constraint Compatibility Analysis], and directly write the judgment in [Final Judgment].

[Historical Constraints]
List the historical constraints that need to be preserved.

[New Constraints]
List the explicit and implicit constraints from the subsequent query.

[Constraint Compatibility Analysis]
Explain whether the new constraints are compatible with, irrelevant to, or in conflict with the historical constraints.

[Final Judgment]
Give the final classification.
</think>
<<class name>>""".strip()


def get_extract_features(item: Dict[str, Any]) -> Dict[str, Any]:
    llm_outputs = common.get_llm_outputs(item)
    features = (
        llm_outputs.get("extract_constraints")
        or llm_outputs.get("extract_features")
        or {}
    )
    return features if isinstance(features, dict) else {}


def build_user_content(item: Dict[str, Any], current_query: str) -> str:
    dialogue_history = common.messages_to_text(item.get("dialogue_history") or [])
    return (
        f"{CLASSIFICATION_PROMPT}\n\n"
        "## Input\n\n"
        "Dialogue history:\n"
        f"{dialogue_history}\n\n"
        "Subsequent user query:\n"
        f"{current_query}"
    )


def normalize_task_judge_text(task_judge: Any) -> str:
    return str(task_judge or "").strip().lower()


TASK_JUDGE_VALUES = {"current_subtask", "current_main_task", "new_task"}
NEW_TASK_JUDGE = "new_task"


def collect_task_judge_stats(items: Iterable[Dict[str, Any]]) -> Counter[str]:
    counts: Counter[str] = Counter()
    for item in items:
        for verify_result in common.get_verify_results(item):
            text = normalize_task_judge_text(verify_result.get("task_judge"))
            if text:
                counts[text] += 1
    return counts


def print_task_judge_stats(task_judge_counts: Counter[str]) -> None:
    print(f"[Stats] task_judge unique variants: {len(task_judge_counts)}")
    for text, count in task_judge_counts.most_common():
        tags = []
        if text == NEW_TASK_JUDGE:
            tags.append("new-task")
        if text not in TASK_JUDGE_VALUES:
            tags.append("unknown")
        tag = f" [{' '.join(tags)}]" if tags else ""
        print(f"[Stats] task_judge: {count:4d} | {text}{tag}")


def is_new_task_judge(task_judge: Any) -> bool:
    return normalize_task_judge_text(task_judge) == NEW_TASK_JUDGE


def new_task_final_judgment_text(
    verify_result: Dict[str, Any],
    label: str,
) -> str:
    reasoning = common.format_value_or_none(verify_result.get("reasoning"))
    return (
        "The subsequent query starts a new task, so there is no need to further "
        "analyze historical constraints, new constraints, or constraint "
        f"compatibility. The judgment basis is: {reasoning} Therefore, the final "
        f"classification is: {label}"
    )


def build_assistant_content(
    item: Dict[str, Any],
    verify_result: Dict[str, Any],
) -> str:
    label = str(item["label"])
    features = get_extract_features(item)

    completed_subtasks = common.get_nested_task_field(
        features,
        "completed_subtasks",
        "completed_subtasks",
    )
    current_subtask = common.get_nested_task_field(
        features,
        "current_subtask",
        "current_subtask",
    )
    new_explicit_constraints = (
        verify_result.get("new_explicit_constraints")
        or verify_result.get("current_explicit_constraints")
    )
    new_implicit_constraints = (
        verify_result.get("new_implicit_constraints")
        or verify_result.get("current_implicit_constraints")
    )

    lines: List[str] = []
    lines.append("[Task Level]")
    lines.append(
        f"First, I extract the completed main tasks from the dialogue history: {common.task_goal_list_text(features.get('completed_main_tasks'))}"
    )
    lines.append(
        f"I also identify the current ongoing main task: {common.task_goal_text(features.get('current_main_task'))}"
    )
    lines.append(
        f"Next, I identify the subtasks already completed in the history: {common.task_goal_list_text(completed_subtasks)}"
    )
    lines.append(
        f"The current subtask being handled is: {common.task_goal_text(current_subtask)}"
    )
    lines.append(
        f"Then I determine the task level continued by the subsequent query: {common.format_value_or_none(verify_result.get('task_judge'))}"
    )

    if is_new_task_judge(verify_result.get("task_judge")):
        lines.append("")
        lines.append("[Final Judgment]")
        lines.append(new_task_final_judgment_text(verify_result, label))
        return f"<think>{chr(10).join(lines)}</think><<{label}>>"

    lines.append("")
    lines.append("[Historical Constraints]")
    lines.append(
        f"At this continued task level, the historical constraints that need to be preserved are: {common.constraints_text(verify_result.get('history'))}"
    )

    lines.append("")
    lines.append("[New Constraints]")
    lines.append(
        f"Looking at the subsequent query itself, its explicit constraints are: {common.constraints_text(new_explicit_constraints)}"
    )
    lines.append(
        f"The constraints that can be implicitly inferred from it are: {common.constraints_text(new_implicit_constraints)}"
    )

    lines.append("")
    lines.append("[Constraint Compatibility Analysis]")
    lines.append(
        f"Based on this information, my judgment process is: {common.format_value_or_none(verify_result.get('reasoning'))}"
    )

    lines.append("")
    lines.append("[Final Judgment]")
    lines.append(f"Therefore, the final classification is: {label}")

    return f"<think>{chr(10).join(lines)}</think><<{label}>>"


def build_train_item(
    item: Dict[str, Any],
    verify_result: Dict[str, Any],
    min_confidence_by_label: Dict[str, int],
    include_metadata: bool,
) -> Optional[Dict[str, Any]]:
    label = item.get("label")
    if label not in common.VALID_LABELS or verify_result.get("label") != label:
        return None

    confidence = common.normalize_confidence(verify_result.get("confidence"))
    if not common.passes_confidence_threshold(
        str(label),
        confidence,
        min_confidence_by_label,
    ):
        return None

    current_query = common.get_current_query(item, verify_result)
    if not current_query:
        print(f"[Warning] {item.get('sample_id')} is missing the subsequent user query; skipped.")
        return None

    messages = [
        {"role": "user", "content": build_user_content(item, current_query)},
        {
            "role": "assistant",
            "content": build_assistant_content(item, verify_result),
        },
    ]

    if not include_metadata:
        return {"messages": messages}

    candidate_id = verify_result.get("candidate_id")
    train_id = str(item.get("sample_id") or item.get("source_id") or "")
    if label == "Implicit Conflict" and candidate_id is not None:
        train_id = f"{train_id}_candidate_{candidate_id}"

    return {
        "id": train_id,
        "source_id": item.get("source_id"),
        "label": label,
        "candidate_id": candidate_id,
        "confidence": confidence,
        "language": item.get("language") or item.get("Language"),
        "messages": messages,
    }


def convert_to_train_data(
    items: Iterable[Dict[str, Any]],
    min_confidence_by_label: Optional[Dict[str, int]] = None,
    include_metadata: bool = False,
) -> List[Dict[str, Any]]:
    items = list(items)
    thresholds = min_confidence_by_label or dict(common.DEFAULT_MIN_CONFIDENCE)
    train_data: List[Dict[str, Any]] = []
    label_counts = {label: 0 for label in sorted(common.VALID_LABELS)}
    language_counts: Dict[str, int] = {}
    skipped = 0
    task_judge_counts = collect_task_judge_stats(items)

    print_task_judge_stats(task_judge_counts)

    for item in items:
        if common.should_skip_item(item):
            skipped += 1
            continue

        verify_results = common.get_verify_results(item)
        if not verify_results:
            skipped += 1
            print(f"[Warning] {item.get('sample_id')} is missing verify.results; skipped.")
            continue

        for verify_result in verify_results:
            train_item = build_train_item(
                item,
                verify_result,
                min_confidence_by_label=thresholds,
                include_metadata=include_metadata,
            )
            if train_item is None:
                skipped += 1
                continue
            train_data.append(train_item)
            label = str(item.get("label"))
            language = str(item.get("language") or item.get("Language") or "Unknown")
            label_counts[label] = label_counts.get(label, 0) + 1
            language_counts[language] = language_counts.get(language, 0) + 1

    print(f"[Done] Generated {len(train_data)} training samples; skipped {skipped} invalid/rejected samples.")
    for label in sorted(label_counts):
        print(f"[Stats] {label}: {label_counts[label]}")
    for language in sorted(language_counts):
        print(f"[Stats] {language}: {language_counts[language]}")
    return train_data


def apply_sample_limit(
    items: List[Dict[str, Any]],
    sample_limit: Optional[int],
) -> List[Dict[str, Any]]:
    if sample_limit is None:
        return items
    if sample_limit < 0:
        raise ValueError("sample_limit must be greater than or equal to zero.")
    return items[:sample_limit]


def group_items_by_source_id(items: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    indexed_items = list(enumerate(items))

    def sort_key(indexed_item: tuple[int, Dict[str, Any]]) -> tuple[int, str, int]:
        index, item = indexed_item
        source_id = item.get("source_id")
        if source_id is None:
            return (1, "", index)
        return (0, str(source_id), index)

    return [item for _, item in sorted(indexed_items, key=sort_key)]


def _sample_limit(value: str) -> Optional[int]:
    if value.lower() == "all":
        return None
    try:
        limit = int(value)
    except ValueError as exc:
        raise argparse.ArgumentTypeError("sample limit must be an integer or 'all'.") from exc
    if limit < 0:
        raise argparse.ArgumentTypeError("sample limit must be non-negative.")
    return limit


def _confidence_threshold(value: str) -> int:
    try:
        threshold = int(value)
    except ValueError as exc:
        raise argparse.ArgumentTypeError("confidence threshold must be an integer.") from exc
    if not 0 <= threshold <= 100:
        raise argparse.ArgumentTypeError("confidence threshold must be between 0 and 100.")
    return threshold


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Convert synthesized Syn-UC samples to SFT messages.",
    )
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT_PATH)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT_PATH)
    parser.add_argument("--format", choices=("json", "jsonl"), default="json")
    parser.add_argument("--sample-limit", type=_sample_limit, default=None)
    parser.add_argument("--include-metadata", action="store_true")
    parser.add_argument(
        "--preserve-input-order",
        action="store_true",
        help="Do not group records by source_id before conversion.",
    )
    parser.add_argument("--min-normal-confidence", type=_confidence_threshold, default=95)
    parser.add_argument("--min-explicit-confidence", type=_confidence_threshold, default=100)
    parser.add_argument("--min-implicit-confidence", type=_confidence_threshold, default=90)
    return parser


def main(argv: Optional[List[str]] = None) -> None:
    args = build_parser().parse_args(argv)
    synthesize_data_list = common.read_jsonl(args.input)
    synthesize_data_list = apply_sample_limit(synthesize_data_list, args.sample_limit)
    print(f"[Info] Loaded {len(synthesize_data_list)} samples from {args.input}")
    if not args.preserve_input_order:
        synthesize_data_list = group_items_by_source_id(synthesize_data_list)
        print("[Info] Grouped input samples by source_id before conversion.")
    thresholds = {
        "Normal Dialogue": args.min_normal_confidence,
        "Explicit Revision": args.min_explicit_confidence,
        "Implicit Conflict": args.min_implicit_confidence,
    }
    output_data_list = convert_to_train_data(
        synthesize_data_list,
        min_confidence_by_label=thresholds,
        include_metadata=args.include_metadata,
    )
    common.write_records(args.output, output_data_list, args.format)
    print(f"[Written] {args.output}")


if __name__ == "__main__":
    main()
